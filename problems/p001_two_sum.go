package problems

// 1. 两数之和（Two Sum）
//
// 题目：
//
//	给定一个整数数组 nums 和一个整数目标值 target，请你在该数组中找出和为目标值
//	target 的那两个整数，并返回它们的数组下标。假设每种输入只会对应一个答案，
//	同一个元素不能重复使用，返回顺序不限。
//
// 思路：
//
//	一边遍历一边把「已经见过的值 -> 下标」记进哈希表。遍历到 nums[i] 时，
//	先查 target-nums[i] 是否出现过：出现过就说明答案就是那对下标，直接返回；
//	没出现过再把 nums[i] 自己存进表里。因为先查后存，天然避免了同一个元素
//	用两次（例如 nums=[3,3], target=6 时第二个 3 查到的是第一个 3 的下标）。
//
// 复杂度：
//
//	时间 O(n)：每个元素最多进表一次、查表一次，均摊 O(1)。
//	空间 O(n)：最坏情况下哈希表要存 n-1 个元素。
//
// 卡点：
//
//  1. 写成「先把整个数组塞进 map，再遍历查找」，会把重复值覆盖掉。比如
//     nums=[3,3], target=6，map 里只剩下 {3:1}，自己配自己就错了。
//     正确做法是一遍走：先查、后存。
//  2. 忘了 target- nums[i] 里的减法方向写反成 nums[i]-target，负数场景
//     直接就查不到（测试里有 nums=[-3,4,3,90], target=0 这种用例）。
//  3. 两个下标相等的自配对没判掉；先查后存的写法能顺手规避，不要额外画蛇添足。
//
// Go 注意点：
//
//   - map 的「二值取法」v, ok := m[key] 是这题的核心写法：用 ok 区分
//     「键存在且值为 0」和「键不存在」，不能靠 v != 0 判断。
//   - 零值陷阱：下标 0 是合法答案，但 map 取不到时返回的也是 0，
//     所以必须用 ok，不能用 idx != 0。
//   - 返回 []int{i, j} 是新建切片，不会和入参 nums 共享底层数组；
//     但调用方仍然可以改这个返回值，题目不要求只读，无需拷贝。
//   - 不用管 map 的遍历顺序，这题压根不遍历 map。
func TwoSum(nums []int, target int) []int {
	seen := make(map[int]int, len(nums))
	for i, v := range nums {
		if j, ok := seen[target-v]; ok {
			return []int{j, i}
		}
		seen[v] = i
	}
	return nil
}
