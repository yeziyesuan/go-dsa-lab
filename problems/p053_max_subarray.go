package problems

// 53. 最大子数组和（Maximum Subarray）
//
// 题目：
//
//	给你一个整数数组 nums，请你找出一个具有最大和的连续子数组（子数组最少
//	包含一个元素），返回其最大和。
//
// 思路：
//
//	Kadane 算法（一趟线性扫描 + 状态压缩的 DP）。设 cur 为「以当前元素结尾的
//	最大子数组和」。对每个 x 只有两个选择：要么把 x 接到前面那段后面（cur+x），
//	要么从 x 自己重新开一段（x）。取较大者作为新的 cur，再用它更新全局答案。
//
//	写成 `if cur < 0 { cur = 0 }` 的版本也常见（先丢弃负贡献前缀，再加 x），
//	两个版本等价；这里保留 cur+x 的形式，因为「重新开一段」的语义更直观，
//	也更容易推广到「限制子数组长度」之类的变形题。
//
//	注意 cur 不能初始化为 0 就完事——当数组全是负数时，最优解是「只取最大的
//	那个负数」，而 0 是空子数组的和，题目不允许空子数组。
//
// 复杂度：
//
//	时间 O(n)：一趟扫描，每个元素一次加法和两次比较。
//	空间 O(1)：只有 cur 和 best 两个变量（DP 的状态被压成了一个变量）。
//
// 卡点：
//
//  1. 空数组没挡掉：cur/best 初始化成 nums[0] 会越界 panic。题目虽然保证
//     数组非空，但签名允许传空切片，测试里也有这一条。
//  2. 全负数数组返回 0：因为把 best 或 cur 初始化成了 0，或者写了
//     `if cur < 0 { cur = 0 }` 却把 best 也带上 0。全负时正确答案是最大的
//     那个负数（比如 [-3,-2,-5] -> -2）。
//  3. 「先更新 best 再更新 cur」还是反过来无所谓，但顺序一旦写成
//     `cur = x; best = max(best, cur)` 而漏了 cur+x 分支，就退化成求最大值。
//  4. best 的初值若写成 math.MinInt 之外的常数（比如 -1），遇到
//     [-2,-1] 这种答案小于该常数的用例就会错。
//
// Go 注意点：
//
//   - 不需要 math 包：best 和 cur 都用 nums[0] 初始化，少一个 import，
//     也天然处理了「最小值可能很小」的问题。
//   - 取最大值手写 if 比调 `max(a, b)` 更早能在各版本 Go 上跑；
//     Go 1.21+ 才有内置的 max（注意它是内置函数而不是 math.Max），
//     W1 阶段统一手写，避免版本差异。
//   - `for _, x := range nums` 里 x 是元素副本，这题只读不改，用 range 最省事。
//
// 进阶：这题也可以用分治做（左半最优 / 右半最优 / 跨中点最优，跨中点部分
// 从 mid 往两边各扫一遍求最大前缀和后缀），复杂度 O(n log n)；还可以用线段树
// 维护「区间和 / 最大前缀 / 最大后缀 / 最大子段和」四元组做多组查询。
// 分治版本 W12 再回来看，那时会配合递归和归并一起讲。
func MaxSubArray(nums []int) int {
	if len(nums) == 0 {
		return 0
	}
	best := nums[0]
	cur := nums[0]
	for _, x := range nums[1:] {
		if cur+x > x {
			cur += x
		} else {
			cur = x
		}
		if cur > best {
			best = cur
		}
	}
	return best
}
