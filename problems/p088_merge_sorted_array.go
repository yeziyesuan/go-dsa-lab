package problems

// 88. 合并两个有序数组（Merge Sorted Array）
//
// 题目：
//
//	给你两个按非递减顺序排列的整数数组 nums1 和 nums2，以及两个整数 m 和 n，
//	分别表示 nums1 和 nums2 中的元素数目。请你把 nums2 合并到 nums1 中，
//	使合并后的数组同样按非递减顺序排列。
//
//	注意：nums1 的长度是 m+n，其中前 m 个是有效元素，后 n 个是 0（占位）。
//	要求原地修改 nums1，不要返回新数组。
//
// 思路：
//
//	三指针 + 从后往前归并。i 指向 nums1 的有效元素末尾（m-1），j 指向 nums2
//	末尾（n-1），k 指向 nums1 的写位置末尾（m+n-1）。每轮比较 nums1[i] 和
//	nums2[j]，把较大的那个写到 nums1[k] 再各自回退。为什么必须从后往前？
//	因为 nums1 前半段既是「待归并的源」又是「结果的目的地」，从前往后会写坏
//	还没读的源数据；从后往前时，k 始终 >= i，被写的位置永远是已经搬走或
//	本就无效的占位区，源数据绝不会被覆盖。
//
//	循环结束的两种情况：j < 0 说明 nums2 全部搬完，nums1 剩下的部分本来
//	就在正确位置，不用管；i < 0 说明 nums1 的有效段搬完了，需要把 nums2
//	剩下的元素直接抄到 nums1 前面。
//
// 复杂度：
//
//	时间 O(m+n)：每轮搬运恰好一个元素，一共 m+n 个。
//	空间 O(1)：三个下标 + 一个临时变量，原地完成。
//
// 卡点：
//
//  1. 贪图好写而「从前往后」归并，把 nums1 里还没读的元素覆盖掉，
//     归并结果开始错乱。这题的核心考点就在这个方向选择上。
//  2. 把「nums1 的长度」误当成 m。nums1 长度是 m+n，有效前缀只有 m 个，
//     所以写位置是 m+n-1、nums1 的末尾指针是 m-1，两者差 n。
//  3. 忘了循环之后处理 i < 0 的收尾：比如 nums2 = [1] 而 nums1 有效段
//     已经全搬完时，需要把 nums2 剩下的元素补到 nums1 前面。
//     反过来的情况（j < 0）不需要任何收尾。
//  4. n == 0 或 m == 0 的边界：n == 0 时压根不用动 nums1；
//     m == 0 时整个 nums2 要抄进去，收尾循环必须能兜住。
//
// Go 注意点：
//
//   - 即使 m == 0，也不能写 `nums1 = nums2`：那只是换了函数内的切片头，
//     调用方看到的 nums1 一点没变。必须 `nums1[k] = nums2[j]` 逐个搬。
//   - 这题签名末尾有个多余空格（`n int) `），gofmt 会规范成正常形式，
//     照抄题目给的签名即可，格式化不改变函数签名。
//   - 收尾可以直接用 copy：`copy(nums1[:j+1], nums2[:j+1])`。
//     这里为了把三指针讲透，用的显式循环，两种写法等价。
//   - 不要在函数里做 `nums1 = append(...)`。append 可能重新分配底层数组，
//     于是修改全丢在函数内；这题要的正是「写回原底层数组」。
func Merge(nums1 []int, m int, nums2 []int, n int) {
	// 越界防线：m、n 与切片长度必须自洽，否则下面所有下标都会算错。
	if m < 0 || n < 0 || m+n > len(nums1) || n > len(nums2) {
		return
	}

	i, j, k := m-1, n-1, m+n-1
	for i >= 0 && j >= 0 {
		if nums1[i] > nums2[j] {
			nums1[k] = nums1[i]
			i--
		} else {
			nums1[k] = nums2[j]
			j--
		}
		k--
	}

	// i < 0：nums1 的有效段搬完了，把 nums2 剩下的按序补到最前面。
	// j < 0：nums2 搬完了，nums1 剩下的本来就在正确位置，无需处理。
	for j >= 0 {
		nums1[k] = nums2[j]
		j--
		k--
	}
}
