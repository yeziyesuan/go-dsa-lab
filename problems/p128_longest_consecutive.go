package problems

// LongestConsecutive 返回 nums 中最长连续序列的长度（128. 最长连续序列）。
//
// 题目：
//
//	给定未排序的整数数组 nums，求最长的连续整数序列长度。序列里的数在原数组中
//	不要求相邻，重复元素只算一次。例如 [100,4,200,1,3,2] 的最长连续序列是
//	1,2,3,4，返回 4；空输入返回 0。
//
// 思路：
//
//	先把所有数丢进 set 去重，然后**只从每个连续段的起点**往右数。
//	起点的定义：num-1 不在 set 里的数。对每个起点不断查 num+1、num+2……直到断开，
//	得到以它开头那段连续序列的长度，全程取最大值。
//
//	为什么这样还是 O(n)：
//	  1. 外层 for 把 set 里每个数看一遍，共 n 次（重复元素已被 set 天然去重）；
//	  2. 内层循环只在 v 是起点时才真正迈步，而它踩过的 v+1、v+2…… 的 v-1 都在 set 里，
//	     所以这些数**永远不会被当成起点再触发一次内层循环**；
//	  3. 于是内层总步数 = 每个数最多被向右访问一次 ≤ n，两段加起来仍是 O(n)。
//	关键就在「只从起点数」：如果对每个数都往右数一遍，就退化成 O(n²)。
//
// 复杂度：
//
//	时间 O(n)：进 set 一遍 + 每个数至多被内层访问一次。
//	空间 O(n)：set 要存下去重后的所有数。
//
// 卡点：
//
//  1. 一开始对每个数都往右数了一遍，写出 O(n²)；要能用「每个数最多被数一次」讲清楚
//     为什么加了起点判断就降到 O(n)，这是本题的面试点。
//  2. 起点判据必须查 v-1（没有前驱才算起点），别糊成 v+1，方向反了容易和「往右数」
//     混着写出死循环。
//  3. 空数组返回 0、单元素返回 1：best 初值取 0 就能自然覆盖，不需要特判。
//
// Go 注意点：
//
//   - map 只当集合用，value 取零大小的 struct{}；不能依赖 map 的遍历顺序（无序），
//     所以内层的连续性只能靠查表判断。
//   - Go 没有 while，用 `for { ... break }` 或带条件的 for 表达「一直往右数」。
//   - cur, n := v, 1 这种多变量短声明在本文件里够用；不要用包级变量存中间状态。
func LongestConsecutive(nums []int) int {
	set := make(map[int]struct{}, len(nums))
	for _, v := range nums {
		set[v] = struct{}{}
	}

	best := 0
	for v := range set {
		if _, ok := set[v-1]; ok {
			continue // v 有前驱，不是起点：它所在的那段会由起点那一轮数完
		}

		cur, n := v, 1
		for {
			if _, ok := set[cur+1]; !ok {
				break
			}
			cur++
			n++
		}
		if n > best {
			best = n
		}
	}
	return best
}
