package problems

// ReverseString 原地反转字节切片 s（LeetCode 344. 反转字符串）。
//
// 题目：编写一个函数，将输入的字符数组 s 原地反转，要求不分配额外的数组空间。
//
// 思路：双指针。i 指向首、j 指向尾，交换 s[i] 与 s[j] 后两指针一起向中间走
// （i++、j--），直到 i >= j 停止。奇数长度时中间那个元素自然不用动。
//
// 复杂度：时间 O(n)，空间 O(1)。
//
// 卡点：
//  1. 循环条件写 i < j。写成 i <= j 时中间元素会自己和自己交换，结果虽然对，
//     但多做一次无意义交换，面试里容易被追问。
//  2. Go 的 for 后置语句只允许「一条语句」，所以不能写 i++, j--，
//     要写成并行赋值 i, j = i+1, j-1。
//  3. 参数必须是 []byte（切片）才能原地改：string 在 Go 里不可变，
//     传 [N]byte 数组则是值拷贝，函数里改了外面看不到。
//
// Go 注意点：
//  1. s[i], s[j] = s[j], s[i] 是 Go 的并行赋值，天生就是交换，不需要临时变量，
//     也不会有「先覆盖后赋值」的经典 C 语言错误。
//  2. []byte 是引用底层数组的切片（含指针、长度、容量），函数内修改直接影响调用方，
//     这正是「原地」能生效的原因。
//  3. 这里按 byte 反转：ASCII 输入没问题；中文等多字节 UTF-8 字符会被拆开，
//     反转后不再是合法的 UTF-8（但「反转两次还原子串」这条性质仍然成立）。
//     要按「字符」反转必须先转成 []rune，详见 p125 注释里的 byte vs rune。
func ReverseString(s []byte) {
	for i, j := 0, len(s)-1; i < j; i, j = i+1, j-1 {
		s[i], s[j] = s[j], s[i]
	}
}
