package problems

// 283. 移动零（Move Zeroes）
//
// 题目：
//
//	给定一个数组 nums，编写一个函数将所有 0 移动到数组的末尾，同时保持非零
//	元素的相对顺序。必须原地操作，不能拷贝额外数组。
//
// 思路：
//
//	快慢指针（同向覆盖）+ 收尾补零。慢指针 k 是「非零元素应该写到的位置」，
//	快指针 i 扫一遍：nums[i] != 0 就写到 nums[k] 并让 k 前进。因为 k <= i
//	恒成立，被覆盖的位置要么是读过的 0，要么是刚搬走的自己，不会丢数据。
//	扫完之后，从 k 到末尾全部填 0，这一步就是「把零挪到后面」。
//
//	（也可以在一趟里用交换：nums[i] != 0 时 swap(nums[i], nums[k]); k++。
//	效果一样，但每遇到一个非零就要写两次数组；先覆盖后补零是各写一次。）
//
// 复杂度：
//
//	时间 O(n)：i 扫一趟 O(n)，补零总共 n-k 次 O(n)，合起来还是 O(n)。
//	空间 O(1)：只有两个下标。
//
// 卡点：
//
//  1. 最容易漏的一步：只做了覆盖、忘了把 nums[k:] 补 0，结果尾部残留着
//     被覆盖前的旧元素。例如 [0,1,0,3,12] 会变成 [1,3,12,3,12]。
//  2. 补零的下标写成 `for i := k; i < len(nums); i++` 里循环变量复用错，
//     或者写成 `i <= len(nums)`，off-by-one 直接越界 panic。
//  3. 空数组 / nil 切片 / 全零：全零时 k 始终是 0，补零循环要把整条切片
//     填一遍，必须能正常工作（别写成「k 为 0 就跳过」）。
//  4. 试图用 `append` 或 `copy` 造新切片返回——这题签名没有返回值，
//     所有修改必须落回参数 nums 的底层数组。
//
// Go 注意点：
//
//   - 函数无返回值，说明「结果只能通过参数切片带出去」。这也是为什么测试
//     可以直接断言传入切片的最终内容。
//   - 切片的长度是不可变的：`nums = append(nums, 0)` 只是在函数内重建了
//     一个切片头，调用方看不到，而且这题本来就不该扩容。原地覆盖才是正解。
//   - 零值判断用 `nums[i] != 0`；Go 里没有 Python 那种真值判断，
//     不能写 `if nums[i]`。
//   - `for i, v := range nums` 里的 v 是副本，想写回必须用 `nums[i] = ...`，
//     不能靠 `v = ...`。
func MoveZeroes(nums []int) {
	k := 0
	for i := 0; i < len(nums); i++ {
		if nums[i] != 0 {
			nums[k] = nums[i]
			k++
		}
	}
	for i := k; i < len(nums); i++ {
		nums[i] = 0
	}
}
