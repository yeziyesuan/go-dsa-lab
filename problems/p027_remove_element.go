package problems

// 27. 移除元素（Remove Element）
//
// 题目：
//
//	给你一个数组 nums 和一个值 val，你需要原地移除所有数值等于 val 的元素，
//	并返回移除后数组的新长度 k。元素的顺序可以改变；必须原地修改，只允许
//	O(1) 额外空间，nums 的前 k 个元素里不能出现 val。
//
// 思路：
//
//	快慢指针（同向覆盖法）。慢指针 k 指向「已通过校验的元素」的下一个待写位置，
//	快指针 i 扫描整个数组。nums[i] != val 就把它搬到 nums[k] 并让 k 前进；
//	nums[i] == val 就跳过、什么都不做，让后面的合法元素把它覆盖掉。
//	循环结束时 k 恰好等于保留下来的元素个数，直接返回。
//
//	（另一种 O(n) 解法是「首尾双指针」：发现 val 就把末尾元素搬过来再缩短区间。
//	因为题目允许元素顺序改变，那种写法写入次数更少，但会打乱相对顺序。
//	这里选同向覆盖法，保持顺序，也更容易和 26 题、283 题串成同一条线。）
//
// 复杂度：
//
//	时间 O(n)：i 只扫一趟，每个元素最多被写入一次。
//	空间 O(1)：只用两个下标。
//
// 卡点：
//
//  1. 空数组 / nil 切片直接返回 0，不然循环外的任何下标访问都会越界。
//  2. 把返回值写成 len(nums)，或者返回后忘了「前 k 个才有效」——题目只保证
//     nums[:k] 里没有 val，k 之后是垃圾数据，不要去断言整条切片。
//  3. 判断写反：条件是「不等于 val 才保留」，写成 == val 会正好把要删的全留下。
//     测试里特意放了全等于 val 和全不等于 val 两种极端。
//  4. k 初值写成 1 而不是 0（从 26 题搬思路时最容易带过来），会白白多留一个
//     元素。
//
// Go 注意点：
//
//   - 原地写入 nums[k] = nums[i] 时，因为 k <= i 恒成立，永远不会覆盖掉
//     还没读过的元素，所以不需要额外数组。
//   - 切片传参是「描述符拷贝」：函数内重新赋值 nums = xxx 不会影响调用方，
//     但改 nums[i] 会影响。这题靠的正是后者。
//   - 题目允许改变顺序，但保持顺序的写法复杂度一样，就不引入排序了；
//     排序只出现在测试里（断言顺序无关时先排序再比较）。
func RemoveElement(nums []int, val int) int {
	k := 0
	for i := 0; i < len(nums); i++ {
		if nums[i] != val {
			nums[k] = nums[i]
			k++
		}
	}
	return k
}
