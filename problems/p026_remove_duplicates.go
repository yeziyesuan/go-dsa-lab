package problems

// 26. 删除有序数组中的重复项（Remove Duplicates from Sorted Array）
//
// 题目：
//
//	给你一个非严格递增排列的数组 nums，请你原地删除重复出现的元素，使每个元素
//	只出现一次，返回删除后数组的新长度 k。必须原地修改输入数组，并使用 O(1)
//	额外空间；nums 的前 k 个元素应当保存去重后的结果，其余内容无所谓。
//
// 思路：
//
//	快慢指针。数组有序，所以所有重复项必然挨在一起。慢指针 k 指向「已确认的
//	去重结果」的下一个待写位置，快指针 i 扫描整个数组。只要 nums[i] 和
//	「上一个保留值」nums[k-1] 不同，就把它写到 nums[k] 并让 k 前进一格。
//	k 同时就是新长度，循环结束后直接返回。
//
// 复杂度：
//
//	时间 O(n)：i 从 0 扫到 n-1，每个元素只比较一次。
//	空间 O(1)：只用了 k 和 i 两个下标，原地覆盖写入。
//
// 卡点：
//
//  1. 忘记处理空数组：k 初始为 0 时若直接访问 nums[k-1] 会越界 panic。
//     先写 `if len(nums) == 0 { return 0 }` 把空输入挡掉。
//  2. 比较对象搞错：拿 nums[i] 去比 nums[i-1] 是有序前提下也成立的写法，
//     但语义上更推荐比 nums[k-1]（上一个**保留**的值），这样即使数组无序
//     也不会把远处的重复值漏掉，思路更稳。
//  3. 写成 `nums[k] = nums[i]; k++` 时忘了 k++，或者把 k 当成下标去
//     取「当前保留值」，导致第一个元素就被自己比较掉。
//  4. 返回值写成 k+1 / len(nums) —— k 就是长度，不要 +1。
//
// Go 注意点：
//
//   - 参数是 []int 切片，`nums[k] = nums[i]` 直接改到底层数组，调用方可见，
//     这正是题目要的「原地」。不需要（也不能）返回新切片。
//   - for range 的 v 是元素副本；这里需要写回 nums，所以必须用下标循环
//     `for i := 1; i < len(nums); i++`，不能靠 v 改数组。
//   - 切片越界会在运行时 panic 而不是编译期报错，空数组分支必须显式写。
//   - 返回的 k 是 int，调用方自己切 nums[:k]；函数内部不要切，避免多一次切片头拷贝。
func RemoveDuplicates(nums []int) int {
	if len(nums) == 0 {
		return 0
	}
	k := 1
	for i := 1; i < len(nums); i++ {
		if nums[i] != nums[k-1] {
			nums[k] = nums[i]
			k++
		}
	}
	return k
}
