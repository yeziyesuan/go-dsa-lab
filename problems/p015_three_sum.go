package problems

import "sort"

// 15. 三数之和（3Sum）
//
// 题目：
//
//	给你一个整数数组 nums，判断是否存在三元组 [nums[i], nums[j], nums[k]]
//	满足 i != j、i != k 且 j != k，同时还满足 nums[i] + nums[j] + nums[k] == 0。
//	请你返回所有和为 0 且不重复的三元组。答案中不可以包含重复的三元组。
//
// 思路：
//
//		排序 + 固定一个数 + 双指针 + 去重。
//
//		1. 先 sort.Ints(nums)。排序带来两个好处：可以用双指针夹逼，以及所有
//		   重复值都挨在一起、方便跳过。
//		2. 枚举第一个数 nums[i]（i 从 0 到 n-3），问题退化为「在 nums[i+1:] 里
//		   找两数之和为 -nums[i]」——就是第 167 题的经典双指针：
//		   左指针 l = i+1，右指针 r = n-1，sum := nums[l] + nums[r]；
//		   sum < 0 说明需要更大的数，l++；sum > 0 说明需要更小的数，r--；
//		   命中就记录答案，两个指针同时内收。
//	  3. 三层去重：
//	     第一层：i > 0 && nums[i] == nums[i-1] 时直接跳过，避免同一个首元素
//	     被枚举两次（同时也就避免了同一组答案重复）。
//	     第二、三层：命中一个解之后，l 要跳过所有和 nums[l] 相同的值、
//	     r 要跳过所有和 nums[r] 相同的值，避免同一个中间/末尾值重复配对。
//
//		剪枝（可选但便宜）：nums[i] > 0 时后面全非负，三数和不可能为 0，直接
//		break；若 nums[i] + nums[i+1] + nums[i+2] > 0（最小的三个都超了），
//		也可以 break。
//
// 复杂度：
//
//	时间 O(n^2)：排序 O(n log n)，外层 n 次，内层双指针每轮 O(n)，整体 O(n^2)。
//	空间 O(1)（不计排序栈和返回结果本身）。Go 的 sort.Ints 用的是 pdqsort，
//	递归栈 O(log n)，一般归入 O(1) 或 O(log n)。
//
// 卡点：
//
//  1. 去重漏掉任意一层都会输出重复三元组。最容易漏的是「命中之后 l/r 只
//     移动一步」——必须写 while 把和当前值相同的全部跳过，否则下一轮还会
//     凑出同一个三元组。
//  2. 首元素去重写成 `nums[i] == nums[i+1]`（预判下一个）而不是
//     `nums[i] == nums[i-1]`（回看上一个）。预判的写法在 i+1 越界和
//     「跳过一组但漏掉另一组」上都容易出错，回看写法更稳。
//  3. 把去重放在「命中之后」而不是「外层循环开头」，然后再补一套临时逻辑，
//     代码就容易乱。统一在外层开头回看去重，内层命中后跳过，职责清晰。
//  4. 结果切片返回 nil 还是空切片：题目对无解时的返回值不敏感，
//     这里统一返回 nil，测试里把 nil 和空切片都归一化再比较。
//  5. 复用底层数组导致的隐蔽 bug：如果返回时用 `append(res, nums[i:...])`
//     这种切片而不是新建 `[]int{...}`，结果会随 nums 后续变化而变化。
//     这里每次都新建一个小切片，安全。
//
// Go 注意点：
//
//   - 排序会修改入参切片（原地排序）。题目允许，但调用方要有心理准备；
//     测试里先拷贝再调用，避免用例之间互相影响。
//   - 结果类型是 [][]int：`res = append(res, []int{a, b, c})` 每次新建
//     长度为 3 的切片，不要 append(nums[l:r+1])。
//   - 无解时返回 nil，len(nil) == 0，调用方用 len() 判断即可，不会 panic。
//   - `sort.Ints` 升序；这题必须升序，降序会让双指针的移动方向反过来。
func ThreeSum(nums []int) [][]int {
	sort.Ints(nums)

	res := [][]int{}
	n := len(nums)

	for i := 0; i+2 < n; i++ {
		// 首元素去重：回看上一个，相同就跳过。
		if i > 0 && nums[i] == nums[i-1] {
			continue
		}
		// 剪枝：排序后 nums[i] 是剩余段最小值，它都大于 0 就不可能凑出 0。
		if nums[i] > 0 {
			break
		}

		l, r := i+1, n-1
		for l < r {
			sum := nums[i] + nums[l] + nums[r]
			switch {
			case sum < 0:
				l++
			case sum > 0:
				r--
			default:
				res = append(res, []int{nums[i], nums[l], nums[r]})
				// 命中后必须跳过重复值，否则会输出重复三元组。
				for l < r && nums[l] == nums[l+1] {
					l++
				}
				for l < r && nums[r] == nums[r-1] {
					r--
				}
				l++
				r--
			}
		}
	}

	if len(res) == 0 {
		return nil
	}
	return res
}
