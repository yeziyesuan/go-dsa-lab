package problems

// 11. 盛最多水的容器（Container With Most Water）
//
// 题目：
//
//	给定一个长度为 n 的整数数组 height。有 n 条垂线，第 i 条线的两个端点是
//	(i, 0) 和 (i, height[i])。找出其中的两条线，使得它们与 x 轴共同构成的
//	容器可以容纳最多的水，返回容器可以储存的最大水量。
//
//	面积 = min(height[l], height[r]) * (r - l)，注意不是两端高度之和，
//	而是被较短的那条边卡住的「短板效应」。
//
// 思路：
//
//	双指针从两端向中间夹逼。初始 l = 0、r = n-1，此时底边最宽。每轮算出
//	当前面积并更新答案，然后**移动较短的那一边**：height[l] < height[r] 就
//	l++，否则 r--。
//
//	为什么移动较短的一边不会漏解（这是本题的灵魂）：
//
//	设当前 h[l] <= h[r]，面积被 h[l] 卡住，为 h[l]*(r-l)。现在考虑「所有以
//	l 为左端点的容器」：它们的宽度最大也就是 r-l（底边再往左已经没有了，
//	因为左端点固定在 l 时，右端点最远只能到当前的 r；而这一轮 l 和 r 都还没
//	动过，r 右边也没有别的下标了）。更严谨地说：固定 l，让右端点取遍
//	l+1..r 的任意值 r'，面积是 min(h[l], h[r']) * (r'-l) <= h[l] * (r'-l)
//	<= h[l] * (r-l)。也就是说，在「l 作为左端点」的所有可能里，当前的
//	(l, r) 已经是面积上界，再也不可能更好。
//
//	既然 h[l] <= h[r] 时「以 l 为端点的最优解」已经被这一轮穷尽并记录，
//	l 就可以安全地淘汰出局（l++），去尝试更短的底边但可能更高的边。
//	每一步都排除掉一个确定不可能再变好的端点，所以指针一定会相遇，
//	而所有可能成为最优解的配对都至少被访问过一次，不漏解。
//
//	反过来说：如果移动的是较长的那一边（h[r]），那么「以 l 为端点的最优解」
//	还没被穷尽就被跳过了，可能漏掉正确答案。
//
// 复杂度：
//
//	时间 O(n)：l 和 r 每轮必有一个移动，最多移动 n-1 次。
//	空间 O(1)：只有 l、r、res 三个变量。
//
// 卡点：
//
//  1. 面积公式写成 `(height[l] + height[r]) * (r - l)`（把短板效应写成了
//     两板之和）。这是最经典的错法，示例 1 会算出 13 而不是 49。
//  2. 移动方向的判断用错变量：写成 `if height[l] > height[r] { l++ }`，
//     即移动了较长边，等于主动跳过候选解。
//  3. 相同时移动哪边？h[l] == h[r] 时两边都可以安全移动（上面证明对任意
//     一边都成立），代码统一走 else 分支即可，不必特殊处理。
//  4. 空数组 / 单元素：没有任何两条线，面积为 0；`for l < r` 循环天然
//     不进入，返回 0，不用额外判断。
//  5. 高度里有 0：合法，面积就是 0，不需要特判。
//
// Go 注意点：
//
//   - 两个高度比较时先取较小值用一个临时变量，或者用内置 min（Go 1.21+）；
//     W1 统一手写三目替代品（Go 没有三目运算符），也就是 if/else 赋给一个
//     变量，别为了「一行写完」把逻辑揉成嵌套 if。
//   - 不要为了省事造一个辅助切片来存高度，这题 O(1) 空间是它的卖点。
//   - `for l < r` 而不是 `l <= r`：相等时宽度为 0、面积为 0，没有意义，
//     还容易在下标上多看一次。
func MaxArea(height []int) int {
	res := 0
	l, r := 0, len(height)-1
	for l < r {
		h := height[l]
		if height[r] < h {
			h = height[r]
		}
		if area := h * (r - l); area > res {
			res = area
		}
		// 移动较短的一边：见上方注释里的证明，这一步不会漏解。
		if height[l] < height[r] {
			l++
		} else {
			r--
		}
	}
	return res
}
